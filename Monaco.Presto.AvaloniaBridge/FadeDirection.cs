namespace Monaco.Presto.AvaloniaBridge;

/// <summary>Which way <see cref="FadeExtension"/> moves the element as it fades.</summary>
public enum FadeDirection
{
    /// <summary>It fades in place.</summary>
    None,

    /// <summary>It moves up.</summary>
    Up,

    /// <summary>It moves down.</summary>
    Down,

    /// <summary>It moves to the left.</summary>
    Left,

    /// <summary>It moves to the right.</summary>
    Right,
}
