using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace PrestoGallery.SnippetGenerator;

/// <summary>Emits <c>PrestoGallery.Showcase.Snippets</c>, one <c>const string</c> per snippet region in the additional files.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class SnippetGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidSnippet = new(
        "PSNIP001", "Invalid snippet region", "{0}", "Snippets", DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".axaml", StringComparison.OrdinalIgnoreCase) || file.Path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            .Select((file, token) =>
            {
                var syntax = file.Path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) ? SnippetSyntax.CSharp : SnippetSyntax.Xaml;
                return (file.Path, Result: SnippetExtractor.Extract(file.GetText(token)?.ToString() ?? "", syntax));
            })
            .Collect();

        context.RegisterSourceOutput(files, static (output, files) =>
        {
            var names = new HashSet<string>();
            var source = new StringBuilder("// <auto-generated/>\nnamespace PrestoGallery.Showcase;\n\npublic static class Snippets\n{\n");

            foreach (var (path, (snippets, errors)) in files.OrderBy(file => file.Path, StringComparer.Ordinal))
            {
                foreach (var (line, message) in errors)
                    output.ReportDiagnostic(Diagnostic.Create(InvalidSnippet, At(path, line), message));

                foreach (var (name, text, line) in snippets)
                {
                    if (!names.Add(name))
                        output.ReportDiagnostic(Diagnostic.Create(InvalidSnippet, At(path, line), $"Snippet '{name}' is defined more than once"));
                    else
                        source.Append("    public const string ").Append(name).Append(" = ").Append(SymbolDisplay.FormatLiteral(text, quote: true)).Append(";\n");
                }
            }

            output.AddSource("Snippets.g.cs", source.Append("}\n").ToString());
        });
    }

    private static Location At(string path, int line) =>
        Location.Create(path, default, new LinePositionSpan(new LinePosition(line - 1, 0), new LinePosition(line - 1, 0)));
}
